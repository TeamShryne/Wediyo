// ---------------------------------------------------------------------------
// Rust + UniFFI integration — MANUAL ONLY, not wired to preBuild
//
// Policy split (per user request):
//   - Rust workflow (.github/workflows/rust.yml) builds libs + UniFFI Kotlin bindings
//     and COMMITS them to `app/src/main/jniLibs/` + `app/src/main/kotlin/uniffi/`
//   - Android workflow (.github/workflows/android.yml) just runs ./gradlew —
//     it USES committed artifacts, does NOT rebuild Rust on every app change.
//
// Keeping these tasks defined lets you run them manually on CI via:
//   ./gradlew cargoBuild   or   ./gradlew uniffiBindgen
// but `preBuild` does NOT depend on them, so APK builds don't regen bindings
// just because you touched `rust/`.
// ---------------------------------------------------------------------------

val rustCrateDir = file("../rust/wediyo_engine")
val jniLibsDir = file("src/main/jniLibs")
val committedUniffiDir = file("src/main/kotlin/uniffi")
val ephemeralUniffiDir = file("build/generated/uniffi")

val cargoBuild by tasks.registering(Exec::class) {
    description = "Build Rust crate for Android targets via cargo-ndk (manual — see rust.yml)"
    group = "rust"
    workingDir(rustCrateDir)
    commandLine(
        "cargo", "ndk",
        "-t", "arm64-v8a",
        "-t", "armeabi-v7a",
        "-t", "x86_64",
        "-o", jniLibsDir.absolutePath,
        "build", "--release"
    )
    onlyIf { System.getenv("CI") == "true" || file("/home/shrawan/.cargo/bin/cargo-ndk").exists() }
    doFirst { jniLibsDir.mkdirs() }
}

val cargoBuildCommit by tasks.registering(Exec::class) {
    description = "Build + generate COMMITTED UniFFI — called by rust.yml"
    group = "rust"
    workingDir(rustCrateDir)
    // This is a convenience umbrella; actual CI calls cargo ndk + uniffi-bindgen directly
    commandLine("echo", "use rust.yml workflow; do not call locally — machine is bad")
}

val uniffiBindgen by tasks.registering(Exec::class) {
    description = "Generate Kotlin bindings via uniffi-bindgen to COMMITTED dir (manual)"
    group = "rust"
    workingDir(rustCrateDir)
    // For proc-macro UniFFI, bindgen inspects compiled .so for metadata.
    // Uses arm64 lib as representative (goblin parses it on x86 host).
    val arm64Lib = jniLibsDir.resolve("arm64-v8a/libwediyo_engine.so")
    // Default to committed dir; rust.yml will call with explicit --out-dir
    commandLine(
        "cargo", "run", "--bin", "uniffi-bindgen",
        "generate",
        "--library", arm64Lib.absolutePath,
        "--language", "kotlin",
        "--out-dir", committedUniffiDir.absolutePath
    )
    onlyIf { arm64Lib.exists() || System.getenv("CI") == "true" }
    doFirst {
        committedUniffiDir.mkdirs()
        ephemeralUniffiDir.mkdirs()
    }
}

